// Regenerates the authoring skill's references, the README host table and the
// tables in docs/plugins.md from the engine's own registries, so the skill and
// docs always describe the engine they ship with. `pnpm build` runs it first;
// CI fails when the committed output differs from a fresh run. Rendering is
// pure; file writes sit in main().

import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import "../src/checks/index.ts";
import { type CheckKind, listChecks, type Tier } from "../src/checks/registry.ts";
import { CANONICAL_EVENTS, type EffectKind } from "../src/core/types.ts";
import { ADAPTERS } from "../src/hosts/index.ts";
import type { HostAdapter } from "../src/hosts/types.ts";

const root = (path: string) => new URL(`../${path}`, import.meta.url);
const REFS = "skills/hookmux/references";
const README = "README.md";
const PLUGIN_DOCS = "docs/plugins.md";
const GENERATED = ["check-kinds.md", "effects.md", "hosts.md", "plugin-format.md"].map((f) => `${REFS}/${f}`);

const TIER_LABEL: Record<Tier, string> = { 0: "0 (in-process)", 1: "1 (subprocess)", 2: "2 (model call)" };

/**
 * Effect fields and behaviour. EffectKind is a type with no runtime registry,
 * so the descriptions live here; the Record type makes a new kind fail to
 * compile until it is described.
 */
const EFFECT_DOCS: Record<EffectKind, { fields: string; behaviour: string }> = {
  inject: {
    fields: "`text`",
    behaviour:
      "Adds the text to the agent's context. Dropped when the host cannot add context on this event or the context budget is used up.",
  },
  block: {
    fields: "`reason`, `suppress_original_prompt` (prompt.submit only, default false)",
    behaviour:
      "Stops the prompt or tool call and shows the reason. The first block in output order wins. With `block_requires_rule` on (the default), a check that is not model-backed must be true. Where the host cannot block, it becomes a notice; where it cannot notify either, it is dropped.",
  },
  notify: {
    fields: "`text`",
    behaviour: "Shows the text to the user, not the agent. Dropped when the host cannot notify on this event.",
  },
};

function generatedNote(source: string): string {
  return `<!-- Generated by scripts/gen-skill-refs.ts from ${source}. Do not edit; run \`pnpm gen:refs\`. -->\n`;
}

/** Escapes text for a Markdown table cell. */
function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function adapters(): HostAdapter[] {
  return Object.values(ADAPTERS).sort((a, b) => a.id.localeCompare(b.id));
}

function renderCheckKinds(kinds: CheckKind[]): string {
  const out = [generatedNote("src/checks"), "# Check kinds", ""];
  out.push(
    "Each check in `[checks.<name>]` names one of these kinds. Cheaper tiers run first. By default a model-backed kind cannot justify a block on its own, and its evidence never reaches a template.",
    "",
    "| Kind | Tier | Output | Model-backed |",
    "|---|---|---|---|",
  );
  for (const k of kinds)
    out.push(`| \`${k.kind}\` | ${TIER_LABEL[k.tier]} | ${k.output} | ${k.modelBacked ? "yes" : "no"} |`);
  for (const k of kinds) {
    out.push("", `## \`${k.kind}\``, "", k.summary, "", "| Option | Meaning |", "|---|---|");
    for (const [name, meaning] of Object.entries(k.options)) out.push(`| \`${name}\` | ${cell(meaning)} |`);
  }
  return `${out.join("\n")}\n`;
}

/** Short kind table for docs/plugins.md; the full option lists live in check-kinds.md. */
function checkSummaryRows(kinds: CheckKind[]): string[] {
  const rows = ["| Kind | Tier | Model-backed | What it does |", "|---|---|---|---|"];
  for (const k of kinds) {
    rows.push(`| \`${k.kind}\` | ${TIER_LABEL[k.tier]} | ${k.modelBacked ? "yes" : "no"} | ${cell(k.summary)} |`);
  }
  return rows;
}

function effectRows(): string[] {
  const rows = ["| Effect | Fields | Behaviour |", "|---|---|---|"];
  for (const [kind, doc] of Object.entries(EFFECT_DOCS))
    rows.push(`| \`${kind}\` | ${doc.fields} | ${doc.behaviour} |`);
  return rows;
}

/** One row per host: the effects it supports on each canonical event. */
function supportRows(hosts: HostAdapter[]): string[] {
  const rows = [`| Host | ${CANONICAL_EVENTS.map((e) => `\`${e}\``).join(" | ")} |`];
  rows.push(`|---|${CANONICAL_EVENTS.map(() => "---").join("|")}|`);
  for (const h of hosts) {
    const cells = CANONICAL_EVENTS.map((e) =>
      h.nativeEvents[e] === null ? "not available" : h.supports[e].join(", ") || "none",
    );
    rows.push(`| ${h.name} | ${cells.join(" | ")} |`);
  }
  return rows;
}

function renderEffects(hosts: HostAdapter[]): string {
  const out = [generatedNote("its effect table and src/hosts"), "# Effects", ""];
  out.push("A plugin lists its effects as `[[then]]` tables with an `effect` key.", "", ...effectRows());
  out.push("", "## Support per host and event", "", ...supportRows(hosts));
  return `${out.join("\n")}\n`;
}

function renderHosts(hosts: HostAdapter[]): string {
  const out = [generatedNote("src/hosts"), "# Hosts", ""];
  out.push(
    "Plugins name canonical events. Each adapter maps them to its client's own hook names. Use a `host` check or a `[host.<id>]` table when a plugin must behave differently on one client.",
  );
  for (const h of hosts) {
    out.push("", `## ${h.name} (\`${h.id}\`)`, "", `Context limit: ${h.contextChars} characters.`, "");
    out.push("| Canonical event | Native event | Effects |", "|---|---|---|");
    for (const e of CANONICAL_EVENTS) {
      const native = h.nativeEvents[e];
      out.push(`| \`${e}\` | ${native ? `\`${native}\`` : "none"} | ${h.supports[e].join(", ") || "none"} |`);
    }
  }
  return `${out.join("\n")}\n`;
}

/**
 * Replaces the lines between `<!-- name:begin -->` and `<!-- name:end -->`.
 * Throws when a marker is missing, so an edited page cannot drop a table silently.
 */
function splice(text: string, file: string, name: string, source: string, rows: string[]): string {
  const begin = `<!-- ${name}:begin -->`;
  const end = `<!-- ${name}:end -->`;
  const start = text.indexOf(begin);
  const stop = text.indexOf(end);
  if (start < 0 || stop < start) throw new Error(`${file} needs ${begin} and ${end} markers`);
  const body = [generatedNote(source).trimEnd(), ...rows].join("\n");
  return `${text.slice(0, start + begin.length)}\n${body}\n${text.slice(stop)}`;
}

/** Reads a repo file, applies the edit, writes it back and returns the new text. */
function rewrite(file: string, edit: (text: string) => string): string {
  const text = edit(readFileSync(root(file), "utf8"));
  writeFileSync(root(file), text);
  return text;
}

/**
 * Biome formats Markdown in this repo (it pads table columns), so the output
 * goes through the same formatter; otherwise `pnpm lint` and the CI drift
 * check would disagree with a fresh run.
 */
function formatMarkdown(files: string[]): void {
  const biome = fileURLToPath(root("node_modules/.bin/biome"));
  execFileSync(biome, ["format", "--write", ...files], {
    cwd: fileURLToPath(root("")),
    stdio: ["ignore", "ignore", "inherit"],
  });
}

function main(): void {
  const hosts = adapters();
  const kinds = listChecks();
  mkdirSync(root(REFS), { recursive: true });
  writeFileSync(root(`${REFS}/check-kinds.md`), renderCheckKinds(kinds));
  writeFileSync(root(`${REFS}/effects.md`), renderEffects(hosts));
  writeFileSync(root(`${REFS}/hosts.md`), renderHosts(hosts));
  rewrite(README, (t) => splice(t, README, "hosts", "src/hosts", supportRows(hosts)));
  const pluginDocs = rewrite(PLUGIN_DOCS, (t) => {
    const withKinds = splice(t, PLUGIN_DOCS, "check-kinds", "src/checks", checkSummaryRows(kinds));
    return splice(withKinds, PLUGIN_DOCS, "effects", "its effect table", effectRows());
  });
  // The skill ships without docs/, so it carries its own copy of the plugin reference.
  writeFileSync(root(`${REFS}/plugin-format.md`), `${generatedNote(PLUGIN_DOCS)}${pluginDocs}`);
  rmSync(root(`${REFS}/examples`), { recursive: true, force: true });
  cpSync(root("examples/moodboard"), root(`${REFS}/examples/moodboard`), { recursive: true });
  formatMarkdown([...GENERATED, README, PLUGIN_DOCS]);
  console.log(`generated ${REFS}, the ${README} host table and the ${PLUGIN_DOCS} tables`);
}

main();
